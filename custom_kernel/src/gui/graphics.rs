impl Graphics {
    // Alpha Blending Helper
    #[inline(always)]
    pub fn blend_colors(bg: u32, fg: u32) -> u32 {
        let alpha = (fg >> 24) & 0xFF;
        if alpha == 255 { return fg; }
        if alpha == 0 { return bg; }

        let inv_alpha = 255 - alpha;

        let r_bg = (bg >> 16) & 0xFF;
        let g_bg = (bg >> 8) & 0xFF;
        let b_bg = bg & 0xFF;

        let r_fg = (fg >> 16) & 0xFF;
        let g_fg = (fg >> 8) & 0xFF;
        let b_fg = fg & 0xFF;

        let r = (r_fg * alpha + r_bg * inv_alpha) / 255;
        let g = (g_fg * alpha + g_bg * inv_alpha) / 255;
        let b = (b_fg * alpha + b_bg * inv_alpha) / 255;

        (0xFF << 24) | (r << 16) | (g << 8) | b
    }

    // Generic plot to a slice (for backbuffer)
    #[inline(always)]
    pub fn plot_pixel_unchecked(buffer: &mut [u32], width: usize, x: usize, y: usize, color: u32) {
        if x < width && y * width + x < buffer.len() {
            let idx = y * width + x;
            // Check for alpha
            if (color >> 24) != 0xFF {
                buffer[idx] = Self::blend_colors(buffer[idx], color);
            } else {
                buffer[idx] = color;
            }
        }
    }

    // Standard VRAM Plot (Legacy/Direct)
    pub fn plot_pixel(x: usize, y: usize, color: Color) {
        unsafe {
            let fb_addr = *video::FRAMEBUFFER_ADDR.lock();
            let fb_width = *video::FRAMEBUFFER_WIDTH.lock();
            let fb_height = *video::FRAMEBUFFER_HEIGHT.lock();
            let fb_pitch = *video::FRAMEBUFFER_PITCH.lock();
            
            if x >= fb_width || y >= fb_height { return; }
            let offset = y * fb_pitch + x * 4;
            let ptr = (fb_addr + offset as u64) as *mut u32;
            *ptr = color.to_u32();
        }
    }

    pub fn draw_rect_to_buffer(buffer: &mut [u32], stride: usize, x: usize, y: usize, w: usize, h: usize, color: u32) {
        for i in 0..h {
            for j in 0..w {
                 Self::plot_pixel_unchecked(buffer, stride, x + j, y + i, color);
            }
        }
    }

    pub fn draw_rounded_rect(buffer: &mut [u32], stride: usize, x: usize, y: usize, w: usize, h: usize, r: usize, color: u32) {
        for i in 0..h {
            for j in 0..w {
                let dx = if j < r { r - j } else if j >= w - r { j - (w - r - 1) } else { 0 };
                let dy = if i < r { r - i } else if i >= h - r { i - (h - r - 1) } else { 0 };
                if dx * dx + dy * dy <= r * r {
                    Self::plot_pixel_unchecked(buffer, stride, x + j, y + i, color);
                }
            }
        }
    }

    pub fn draw_shadow(buffer: &mut [u32], stride: usize, x: usize, y: usize, w: usize, h: usize, size: usize) {
        for s in 1..=size {
            let alpha = (32 * (size - s + 1) / size) as u32;
            let shadow_col = (alpha << 24) | 0x000000;
            // Draw bottom and right shadow edges
            Self::draw_rect_to_buffer(buffer, stride, x + s, y + h, w, 1, shadow_col);
            Self::draw_rect_to_buffer(buffer, stride, x + w, y + s, 1, h, shadow_col);
        }
    }

    pub fn draw_gradient_h(buffer: &mut [u32], stride: usize, x: usize, y: usize, w: usize, h: usize, c1: u32, c2: u32) {
        let r1 = (c1 >> 16) & 0xFF;
        let g1 = (c1 >> 8) & 0xFF;
        let b1 = c1 & 0xFF;
        let r2 = (c2 >> 16) & 0xFF;
        let g2 = (c2 >> 8) & 0xFF;
        let b2 = c2 & 0xFF;

        for j in 0..w {
            let r = r1 as i32 + (r2 as i32 - r1 as i32) * j as i32 / w as i32;
            let g = g1 as i32 + (g2 as i32 - g1 as i32) * j as i32 / w as i32;
            let b = b1 as i32 + (b2 as i32 - b1 as i32) * j as i32 / w as i32;
            let col = (0xFF << 24) | ((r as u32) << 16) | ((g as u32) << 8) | (b as u32);
            for i in 0..h {
                Self::plot_pixel_unchecked(buffer, stride, x + j, y + i, col);
            }
        }
    }

    pub fn draw_text(buffer: &mut [u32], stride: usize, x: usize, y: usize, text: &str, color: u32) {
        let mut cx = x;
        for c in text.chars() {
            let idx = (c as usize) & 0x7F;
            let glyph = FONT_8X8[idx];
            for row in 0..8 {
                let row_data = glyph[row];
                for col in 0..8 {
                    if (row_data >> (7 - col)) & 1 != 0 {
                        Self::plot_pixel_unchecked(buffer, stride, cx + col, y + row, color);
                    }
                }
            }
            cx += 8;
        }
    }
    
    pub fn copy_buffer(target: &mut [u32], t_stride: usize, src: &[u32], s_stride: usize, dx: usize, dy: usize, w: usize, h: usize) {
        for i in 0..h {
            for j in 0..w {
                if i * s_stride + j < src.len() {
                     let col = src[i * s_stride + j];
                     // Alpha check
                     if (col >> 24) != 0 {
                        Self::plot_pixel_unchecked(target, t_stride, dx + j, dy + i, col);
                     }
                }
            }
        }
    }

    pub fn fill_rect(x: usize, y: usize, w: usize, h: usize, color: Color) {
        for i in 0..h {
            for j in 0..w {
                Self::plot_pixel(x + j, y + i, color);
            }
        }
    }
    
    // Fast Rect for clearing screen or solid windows
    pub fn fill_screen(color: Color) {
        let w = *video::FRAMEBUFFER_WIDTH.lock();
        let h = *video::FRAMEBUFFER_HEIGHT.lock();
        Self::fill_rect(0, 0, w, h, color);
    }
    
    pub fn draw_line(x0: isize, y0: isize, x1: isize, y1: isize, color: Color) {
        let mut x0 = x0;
        let mut y0 = y0;
        let dx = if x1 > x0 { x1 - x0 } else { x0 - x1 };
        let dy = if y1 > y0 { y0 - y1 } else { y1 - y0 };
        let sx = if x0 < x1 { 1 } else { -1 };
        let sy = if y0 < y1 { 1 } else { -1 };
        let mut err = dx + dy;

        loop {
            if x0 >= 0 && y0 >= 0 {
                 Self::plot_pixel(x0 as usize, y0 as usize, color);
            }
            if x0 == x1 && y0 == y1 { break; }
            let e2 = 2 * err;
            if e2 >= dy {
                err += dy;
                x0 += sx;
            }
            if e2 <= dx {
                err += dx;
                y0 += sy;
            }
        }
    }
    
    pub fn blit(x: usize, y: usize, w: usize, h: usize, src: &[u32]) {
        for i in 0..h {
            for j in 0..w {
                if i * w + j >= src.len() { break; }
                let color_val = src[i * w + j];
                if (color_val >> 24) != 0 {
                    let color = Color::from_hex(color_val);
                    Self::plot_pixel(x + j, y + i, color);
                }
            }
        }
    }
}
